        val q = QrEncoder.encode(text.toByteArray(Charsets.UTF_8), ecc, mask, minVersion = version)
        assertEquals(version, q.version)
        val rows = (0 until q.size).map { y -> (0 until q.size).joinToString("") { x -> if (q[x, y]) "1" else "0" } }
        assertEquals(expected, rows)
    }

